#define ST7789_DISPON   0x29 // recover from DISPLAY OFF mode.
#define ST7789_CASET    0x2A // Column Address Set
#define ST7789_RASET    0x2B // Row Address Aset
#define ST7789_RAMWR    0x2C // Memory Write
#define ST7789_MADCTL   0x36 // Memory Address Access Control
#define ST7789_COLMOD   0x3A // Interface Pixel Format


